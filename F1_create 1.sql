CREATE TABLE Driver_Team (
    driver_team_id  INTEGER   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    driver_id       INTEGER   NOT NULL,
    team_id         INTEGER   NOT NULL,
    season_year     INTEGER   NOT NULL,
    car_number      INTEGER   NOT NULL,
    joined_date     DATE      NOT NULL,
    left_date       DATE      NULL,
    CONSTRAINT uq_driver_season        UNIQUE (driver_id, season_year),
    CONSTRAINT uq_team_car_season      UNIQUE (team_id, car_number, season_year),
    CONSTRAINT chk_dt_season           CHECK (season_year >= 1950),
    CONSTRAINT chk_car                 CHECK (car_number BETWEEN 0 AND 99),
    CONSTRAINT chk_dates               CHECK (left_date IS NULL OR left_date >= joined_date),
    CONSTRAINT Driver_Team_pk          PRIMARY KEY (driver_team_id),
    CONSTRAINT fk_dt_driver            FOREIGN KEY (driver_id)
        REFERENCES Drivers (driver_id) ON DELETE CASCADE,
    CONSTRAINT fk_dt_team              FOREIGN KEY (team_id)
        REFERENCES Teams (team_id) ON DELETE CASCADE
);

CREATE TABLE Races (
    race_id       INTEGER        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    circuit_id    INTEGER        NOT NULL,
    season_year   INTEGER        NOT NULL,
    round_number  INTEGER        NOT NULL,
    name          VARCHAR2(100)  NOT NULL,
