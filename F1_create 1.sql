CREATE TABLE Results (
    result_id          INTEGER       GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    race_id            INTEGER       NOT NULL,
    driver_id          INTEGER       NOT NULL,
    team_id            INTEGER       NOT NULL,
    grid_position      INTEGER       NULL,
    finish_position    INTEGER       NULL,
    points_awarded     INTEGER       DEFAULT 0 NOT NULL,
    status             VARCHAR2(30)  NOT NULL,
    fastest_lap_rank   INTEGER       NULL,
    race_time_seconds  NUMBER(10,3)  NULL,
    CONSTRAINT uq_race_driver      UNIQUE (race_id, driver_id),
    CONSTRAINT uq_race_finish      UNIQUE (race_id, finish_position),
    CONSTRAINT chk_grid            CHECK (grid_position IS NULL OR grid_position > 0),
    CONSTRAINT chk_finish          CHECK (finish_position IS NULL OR finish_position > 0),
    CONSTRAINT chk_points          CHECK (points_awarded >= 0),
    CONSTRAINT chk_flr             CHECK (fastest_lap_rank IS NULL OR fastest_lap_rank > 0),
    CONSTRAINT chk_time            CHECK (race_time_seconds IS NULL OR race_time_seconds > 0),
    CONSTRAINT chk_result_status   CHECK (status IN ('finished','dnf','dns','dsq','lapped')),
    CONSTRAINT Results_pk          PRIMARY KEY (result_id),
    CONSTRAINT fk_res_driver       FOREIGN KEY (driver_id)
        REFERENCES Drivers (driver_id) ON DELETE CASCADE,
    CONSTRAINT fk_res_race         FOREIGN KEY (race_id)
        REFERENCES Races (race_id) ON DELETE CASCADE,
    CONSTRAINT fk_res_team         FOREIGN KEY (team_id)
        REFERENCES Teams (team_id) ON DELETE CASCADE
);

