    status        VARCHAR2(20)   DEFAULT 'scheduled' NOT NULL,
    CONSTRAINT uq_race_season_round    UNIQUE (season_year, round_number),
    CONSTRAINT chk_season              CHECK (season_year >= 1950),
    CONSTRAINT chk_round               CHECK (round_number BETWEEN 1 AND 30),
    CONSTRAINT chk_race_status         CHECK (status IN ('scheduled','completed','cancelled')),
    CONSTRAINT Races_pk                PRIMARY KEY (race_id),
    CONSTRAINT fk_race_circuit         FOREIGN KEY (circuit_id)
