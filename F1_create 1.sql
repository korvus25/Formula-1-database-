CREATE TABLE Circuits (
    circuit_id    INTEGER          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR2(100)    NOT NULL,
    location      VARCHAR2(100)    NOT NULL,
    country       VARCHAR2(50)     NOT NULL,
    length_km     NUMBER(5,3)      NOT NULL,
    total_laps    INTEGER          NOT NULL,
    circuit_type  VARCHAR2(20)     DEFAULT 'permanent' NOT NULL,
    CONSTRAINT AK_circuits_name    UNIQUE (name),
    CONSTRAINT chk_length          CHECK (length_km > 0),
    CONSTRAINT chk_laps            CHECK (total_laps > 0),
    CONSTRAINT chk_circuit_type    CHECK (circuit_type IN ('permanent','street','hybrid')),
    CONSTRAINT Circuits_pk         PRIMARY KEY (circuit_id)
);

CREATE TABLE Teams (
    team_id                    INTEGER        GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name                       VARCHAR2(100)  NOT NULL,
    base_country               VARCHAR2(50)   NOT NULL,
    constructors_championships INTEGER        DEFAULT 0 NOT NULL,
    founded_year               INTEGER        NOT NULL,
    CONSTRAINT AK_teams_name           UNIQUE (name),
    CONSTRAINT chk_titles              CHECK (constructors_championships >= 0),
    CONSTRAINT chk_founded_year_min    CHECK (founded_year >= 1950),
    CONSTRAINT Teams_pk                PRIMARY KEY (team_id)
);

